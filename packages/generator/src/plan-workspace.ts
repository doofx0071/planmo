/**
 * Full planning-workspace renderer (P05-02 extension).
 *
 * The Phase 05 renderers originally produced the plan spine only (roadmap,
 * tracker, phase docs, handoff template, standards, context, policies). A
 * workspace with just those leaves an agent nowhere to record architecture,
 * requirements, design decisions, risks, test strategy or the task list —
 * so this module renders the rest of the canonical planning workspace:
 *
 *   planning/README.md  MASTER-PLAN.md  DECISIONS.md  OPEN-QUESTIONS.md
 *   planning/RISKS.md   REQUIREMENTS-TRACEABILITY.md  tasks.csv
 *   planning/architecture/{ARCHITECTURE,DOMAIN-MODEL,SECURITY-PRIVACY,STATE-MACHINES}.md
 *   planning/compliance/POLICY-REGISTER.md
 *   planning/design/{DESIGN-BRIEF,DESIGN-SYSTEM}.md
 *   planning/prompts/{README,phase-prompt}.md
 *   planning/requirements/PRODUCT-REQUIREMENTS.md
 *   planning/testing/TEST-STRATEGY.md
 *
 * Ownership follows ADR-0016 and is chosen per document, not per folder:
 *   - `generated` — derived entirely from the IR; PlanMo owns every byte and
 *     refreshes it on regeneration (README, MASTER-PLAN, traceability, task
 *     list, architecture, compliance, design, requirements, testing).
 *   - `seeded`    — PlanMo writes a useful starting point once, then the user
 *     owns the file; regeneration never touches it (DECISIONS, OPEN-QUESTIONS,
 *     RISKS, prompts). These accumulate human decisions, so rewriting them
 *     would destroy the only copy.
 *
 * Every renderer is pure: no clock, no randomness, no filesystem, no absolute
 * paths. Identical IR always produces byte-identical artifacts.
 */

interface DocumentSpec {
  path: string;
  ownership: 'generated' | 'seeded';
  render: (ir: PlanningIR) => string;
}

/** Join lines and end with exactly one trailing newline. */
function doc(lines: readonly string[]): string {
  return `${lines.join('\n').trimEnd()}\n`;
}

/** Human label for the project, used in prose. */
function projectName(ir: PlanningIR): string {
  return ir.project.project.name;
}

/** `key: value` bullets for whichever stack keys the project declares. */
function stackLines(ir: PlanningIR): string[] {
  const stack = ir.project.stack;
  if (!stack) return ['_No stack declared in `.planmo/project.yml`._'];
  const order = ['language', 'runtime', 'frontend', 'backend', 'database', 'test', 'ci'] as const;
  const lines: string[] = [];
  for (const key of order) {
    const value = stack[key];
    if (value !== undefined) lines.push(`- ${key}: ${value}`);
  }
  return lines.length > 0 ? lines : ['_No stack declared in `.planmo/project.yml`._'];
}

/** The declared design block, or null when the project has none. */
function design(ir: PlanningIR): NonNullable<PlanningIR['project']['design']> | null {
  return ir.project.design ?? null;
}

/** Test gates: the profile's list, or the documented default. */
function gates(ir: PlanningIR): readonly string[] {
  return ir.profile ? ir.profile.gates : ['unit tests', 'typecheck', 'lint', 'format:check'];
}

