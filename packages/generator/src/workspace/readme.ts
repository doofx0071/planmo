import type { PlanningIR } from '../ir.js';
import { policyClassesInUse } from '../standards-context.js';
import { doc, projectName } from './shared.js';

/**
 * The folder table, derived from what the renderers actually emit.
 *
 * `policies/` is the one conditional folder: it exists only when a standard
 * class has applicable rules, which needs a pack selected. Deriving the row from
 * the same predicate the policy renderer uses means the generated README can
 * never again list a folder that is not there.
 */
function folderRows(ir: PlanningIR): string[] {
  const rows: [string, string][] = [
    ['`architecture/`', 'system shape, domain model, security & privacy, state machines'],
    ['`compliance/`', 'policy register'],
    ['`design/`', 'design brief and design system'],
    ['`handoffs/`', 'per-phase handoff records (template provided)'],
    ['`phases/`', 'one document per planned phase'],
  ];
  if (policyClassesInUse(ir).length > 0) {
    rows.push(['`policies/`', 'one document per standard class in use']);
  }
  rows.push(
    ['`prompts/`', 'agent prompts for this project'],
    ['`requirements/`', 'product requirements'],
    ['`testing/`', 'test strategy'],
  );
  return rows.map(([folder, contents]) => `| ${folder} | ${contents} |`);
}

export function renderReadme(ir: PlanningIR): string {
  return doc([
    `# ${projectName(ir)} — planning workspace`,
    '',
    'This directory is the agent-ready plan for the project. It is generated by',
    'PlanMo from `.planmo/project.yml`; `planmo generate` refreshes the',
    'generated documents and never touches the ones you own.',
    '',
    '## Start here',
    '',
    '- `MASTER-PLAN.md` — the goal, scope and phase spine.',
    '- `ROADMAP.md` — the detailed phase list with objectives.',
    '- `TRACKER.md` and `tasks.csv` — the canonical task list and status.',
    '- `CONTEXT.md` — project, stack, design and planning context.',
    '- `STANDARDS.md` — the standards selected for this project.',
    '',
    '## Documents you own',
    '',
    'These are seeded once and never regenerated — edit them freely:',
    '',
    '- `DECISIONS.md` — the decision log (ADR-style).',
    '- `OPEN-QUESTIONS.md` — questions that block or shape the work.',
    '- `RISKS.md` — the risk register.',
    '- `prompts/` — the prompts used to drive agents on this project.',
    '',
    '## Folders',
    '',
    'Only the folders that were actually generated are listed.',
    '',
    '| Folder | Contents |',
    '|---|---|',
    ...folderRows(ir),
    '',
    '## Rules',
    '',
    '- A task is DONE only after acceptance criteria, tests/evidence, docs and',
    '  traceability are satisfied.',
    `- Phases are ${ir.phaseMode}.`,
    '- Generated files are owned by PlanMo; user-owned files are never overwritten.',
  ]);
}
