import { mkdtemp, readFile, rm, writeFile, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { createMockProvider } from '@planmo/ai';
import { PLAN_PATH } from '@planmo/schema';
import { run } from './index.js';
import { readPlanDocument, renderPlanSummary, runPlan, serializePlan } from './plan.js';

/**
 * `planmo plan` records the plan document, once, and writes nothing on any failure
 * path. These tests drive the real adapter against a real generated workspace, so
 * the persistence path — collisions, dry runs, and the leave-it-alone guarantee —
 * is exercised rather than stubbed.
 */

const roots: string[] = [];
afterEach(async () => {
  for (const root of roots.splice(0)) await rm(root, { recursive: true, force: true });
});

function capture() {
  const out: string[] = [];
  const err: string[] = [];
  return {
    io: { out: (line: string) => out.push(line), err: (line: string) => err.push(line) },
    out,
    err,
  };
}

/** A real workspace, generated by the real CLI. */
async function workspace(): Promise<string> {
  const root = await mkdtemp(join(tmpdir(), 'planmo-plan-'));
  roots.push(root);
  await run(['init', root, '--yes'], capture().io);
  return root;
}

const validPlanJson = (overrides: Record<string, unknown> = {}): string =>
  JSON.stringify({
    schemaVersion: 1,
    idea: 'Build a thing',
    provider: { id: 'mock', model: 'mock' },
    generatedAt: null,
    phases: [
      {
        id: '00',
        title: 'Foundation',
        objective: 'Lay the foundation',
        exitCriteria: ['It holds'],
        tasks: [
          {
            id: 'P00-01',
            title: 'Do the thing',
            priority: 'MUST',
            acceptance: ['The thing works'],
            requirements: [],
            verification: { required: true, checks: ['unit tests'] },
          },
        ],
      },
    ],
    openQuestions: ['Which database?'],
    assumptions: ['The team knows TypeScript'],
    ...overrides,
  });

const options = (root: string, text: string) => ({
  root,
  idea: 'Build a thing',
  provider: createMockProvider({ text }),
  providerId: 'mock',
  model: 'mock',
});

describe('planmo plan — recording the plan document', () => {
  it('writes the plan document to .planmo/plan.yml', async () => {
    const root = await workspace();
    const outcome = await runPlan(options(root, validPlanJson()));

    expect(outcome.ok).toBe(true);
    expect(outcome.written).toContain(PLAN_PATH);

    const onDisk = await readPlanDocument(root);
    expect(onDisk?.phases).toHaveLength(1);
    // The author is recorded in the document itself, not just in the log.
    expect(onDisk?.provider).toEqual({ id: 'mock', model: 'mock' });
  });

  it('writes NOTHING when the plan fails validation, and leaves an existing plan intact', async () => {
    const root = await workspace();
    // A good plan first.
    const first = await runPlan(options(root, validPlanJson()));
    expect(first.ok).toBe(true);
    const before = await readFile(join(root, PLAN_PATH), 'utf8');

    // Now a model that returns rubbish.
    const second = await runPlan(options(root, 'I cannot help with that.'));
    expect(second.ok).toBe(false);
    expect(second.written).toEqual([]);
    expect(second.plan).toBeNull();

    // The last valid plan must be byte-identical — spec §19.
    expect(await readFile(join(root, PLAN_PATH), 'utf8')).toBe(before);
  });

  it('writes nothing at all when there was no previous plan', async () => {
    const root = await workspace();
    const outcome = await runPlan(options(root, '{"schemaVersion":1}'));
    expect(outcome.ok).toBe(false);
    await expect(readFile(join(root, PLAN_PATH), 'utf8')).rejects.toThrow();
  });

  it('refuses to overwrite a plan the user owns, and reports the collision', async () => {
    const root = await workspace();
    await runPlan(options(root, validPlanJson()));
    const before = await readFile(join(root, PLAN_PATH), 'utf8');

    const second = await runPlan(options(root, validPlanJson({ idea: 'A different idea' })));
    expect(second.collisions).toContain(PLAN_PATH);
    expect(await readFile(join(root, PLAN_PATH), 'utf8')).toBe(before);
  });

  it('overwrites when explicitly allowed', async () => {
    const root = await workspace();
    await runPlan(options(root, validPlanJson()));
    const second = await runPlan({
      ...options(root, validPlanJson({ idea: 'A different idea' })),
      allowOverwrite: true,
    });
    expect(second.collisions).toEqual([]);
    expect((await readPlanDocument(root))?.idea).toBe('A different idea');
  });

  it('writes nothing on a dry run, but still reports the plan', async () => {
    const root = await workspace();
    const outcome = await runPlan({ ...options(root, validPlanJson()), dryRun: true });
    expect(outcome.ok).toBe(true);
    expect(outcome.plan).not.toBeNull();
    await expect(readFile(join(root, PLAN_PATH), 'utf8')).rejects.toThrow();
  });

  it('refuses to plan outside a workspace', async () => {
    const root = await mkdtemp(join(tmpdir(), 'planmo-empty-'));
    roots.push(root);
    // `readStatus` raises ProjectNotFoundError before this adapter gets a chance to
    // wrap it, which is what the CLI's exit-3 mapping keys on — so the contract
    // being tested is that the error is that type, not its exact wording.
    await expect(runPlan(options(root, validPlanJson()))).rejects.toThrow(
      /no PlanMo project found/,
    );
  });

  it('serialises deterministically — the same plan yields the same bytes', async () => {
    const root = await workspace();
    const first = await runPlan(options(root, validPlanJson()));
    const again = await runPlan({ ...options(root, validPlanJson()), dryRun: true });
    expect(serializePlan(first.plan!)).toBe(serializePlan(again.plan!));
  });
});

describe('renderPlanSummary', () => {
  it('reports real counts, and shows assumptions and open questions rather than burying them', async () => {
    const root = await workspace();
    const outcome = await runPlan(options(root, validPlanJson()));
    expect(outcome.text).toContain('phases: 1');
    expect(outcome.text).toContain('tasks: 1');
    expect(outcome.text).toContain('author: mock / mock');
    expect(outcome.text).toContain('Which database?');
    expect(outcome.text).toContain('The team knows TypeScript');
    expect(outcome.text).toContain('planmo generate');
  });

  it('says plainly that a failed plan wrote nothing', async () => {
    const root = await workspace();
    const outcome = await runPlan(options(root, 'nope'));
    expect(outcome.text).toContain('FAILED');
    expect(outcome.text).toContain('nothing was written');
    expect(renderPlanSummary(outcome)).toContain('PLN-100');
  });
});
